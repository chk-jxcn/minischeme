/**
 * @file gen_msbc.c
 * @brief Build-time generator of the MSBC images the test suites load.
 *
 *     gen_msbc compiler <scm-dir> <out.h>   -> compiler_msbc.h (compiler_msbc_data)
 *     gen_msbc init     <scm-dir> <out.h>   -> init_msbc.h     (init_msbc_data)
 *
 * "compiler" compiles <scm-dir>/compiler.scm followed by init.scm into one
 * portable CodeObj: the standalone compiler the WebREPL runs (the reference
 * repository's web_repl/wasm/compiler_msbc.h). "init" compiles the runtime
 * forms of init.scm (macros are expanded on the host) into the lean runtime
 * library of the device profile (the reference's web_repl/init_msbc.h).
 *
 * It must be linked with a core built with -DMINISCHEME_EMBED_INIT: the
 * embedded init image provides read-from-string, macro-expand and
 * compile-to-code. The output only depends on the Scheme sources, not on the
 * word size of the host that runs this tool (MSBC is a portable format).
 */

#include "minischeme.h"
#include "minischeme_internal.h"
#include "msbc.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Scheme string literal of a file path (forward slashes, quotes escaped) */
static void scheme_path(char *out, size_t cap, const char *dir, const char *file) {
    char raw[512];
    snprintf(raw, sizeof(raw), "%s/%s", dir, file);
    size_t n = 0;
    for (const char *p = raw; *p && n + 3 < cap; p++) {
        char c = *p == '\\' ? '/' : *p;
        if (c == '"') out[n++] = '\\';
        out[n++] = c;
    }
    out[n] = '\0';
}

static int write_header(const char *out_path, const char *guard, const char *name,
                        const char *what, const uint8_t *buf, size_t len) {
    FILE *fp = fopen(out_path, "w");
    if (!fp) {
        fprintf(stderr, "gen_msbc: cannot open %s for writing\n", out_path);
        return 1;
    }
    fprintf(fp, "/* Auto-generated by tools/gen_msbc.c (%s). DO NOT EDIT. */\n", what);
    fprintf(fp, "#ifndef %s\n#define %s\n\n#include <stdint.h>\n#include <stddef.h>\n\n", guard, guard);
    fprintf(fp, "static const uint8_t %s_data[] = {\n", name);
    for (size_t i = 0; i < len; i++) {
        if (i % 16 == 0) fprintf(fp, "    ");
        fprintf(fp, "0x%02x", buf[i]);
        if (i + 1 < len) fprintf(fp, ", ");
        if (i % 16 == 15 || i + 1 == len) fprintf(fp, "\n");
    }
    fprintf(fp, "};\n\nstatic const size_t %s_len = %lu;\n\n#endif /* %s */\n", name, (unsigned long)len, guard);
    if (fclose(fp) != 0) {
        fprintf(stderr, "gen_msbc: failed to write %s\n", out_path);
        return 1;
    }
    return 0;
}

int main(int argc, char **argv) {
    if (argc != 4 || (strcmp(argv[1], "compiler") != 0 && strcmp(argv[1], "init") != 0)) {
        fprintf(stderr, "usage: %s compiler|init <scm-dir> <out.h>\n", argv[0]);
        return 2;
    }
    bool compiler = strcmp(argv[1], "compiler") == 0;
    char comp_path[600], init_path[600];
    scheme_path(comp_path, sizeof(comp_path), argv[2], "compiler.scm");
    scheme_path(init_path, sizeof(init_path), argv[2], "init.scm");

    static char script[4096];
    if (compiler) {
        snprintf(script, sizeof(script),
                 "(define comp-exprs (read-from-string (%%read-file-string \"%s\")))\n"
                 "(define init-exprs (read-from-string (%%read-file-string \"%s\")))\n"
                 /* the compiler first (it defines %%compile-source-to-code), then init;
                  * init's macro definitions are kept for eval at run time */
                 "(define expanded-comp (map (lambda (e) (macro-expand e)) comp-exprs))\n"
                 "(define transformed-init\n"
                 "  (map (lambda (e)\n"
                 "         (if (and (pair? e) (or (eq? (car e) 'define-syntax) (eq? (car e) 'define-macro)))\n"
                 "             (list 'eval (list 'quote e))\n"
                 "             e))\n"
                 "       init-exprs))\n"
                 "(define *gen-code* (compile-to-code (cons 'begin (append expanded-comp transformed-init))))\n",
                 comp_path, init_path);
    } else {
        snprintf(script, sizeof(script),
                 "(load \"%s\")\n"
                 "(define init-exprs (read-from-string (%%read-file-string \"%s\")))\n"
                 /* macros are expanded at compile time on the host */
                 "(define runtime-forms\n"
                 "  (filter (lambda (e)\n"
                 "            (not (and (pair? e) (or (eq? (car e) 'define-syntax) (eq? (car e) 'define-macro)))))\n"
                 "          init-exprs))\n"
                 "(define *gen-code* (compile-to-code (cons 'begin (map (lambda (e) (optimize-ast (macro-expand e))) runtime-forms))))\n",
                 init_path, init_path);
    }

    MiniVM *vm = mini_create(8 * 1024 * 1024);
    if (!vm) {
        fprintf(stderr, "gen_msbc: failed to create the VM\n");
        return 1;
    }
    mini_eval_string(vm, script);
    if (mini_get_error(vm)) {
        fprintf(stderr, "gen_msbc: %s\n", mini_get_error(vm));
        mini_destroy(vm);
        return 1;
    }
    Value code = env_lookup_name(vm, "*gen-code*");
    if (!mini_is_code(code)) {
        fprintf(stderr, "gen_msbc: the build script did not produce a code object\n");
        mini_destroy(vm);
        return 1;
    }
    uint8_t *buf = NULL;
    size_t len = 0;
    if (!msbc_serialize(vm, code, &buf, &len)) {
        fprintf(stderr, "gen_msbc: MSBC serialization failed\n");
        mini_destroy(vm);
        return 1;
    }
    int rc = compiler
        ? write_header(argv[3], "COMPILER_MSBC_H", "compiler_msbc", "scm/compiler.scm + scm/init.scm", buf, len)
        : write_header(argv[3], "INIT_MSBC_H", "init_msbc", "runtime forms of scm/init.scm", buf, len);
    if (rc == 0) printf("gen_msbc: %s: %lu bytes of MSBC\n", argv[3], (unsigned long)len);
    free(buf);
    mini_destroy(vm);
    return rc;
}
